    def test_golden_trace_and_tamper_detection(self) -> None:
        value = fixture()
        trace = value["runtime"]["conformanceTraces"][0]
        self.assertEqual(
            trace["expected"],
            Interpreter(value).execute(trace["inputEvents"], trace.get("initialState")),
        )
        self.assertEqual([], verify_trace(value, trace))
        corrupted = copy.deepcopy(trace)
        key = "urn:vao:fixture:kinoorgel:state:tibia-enabled"
        corrupted["expected"]["state"][key] = not corrupted["expected"]["state"][key]
        self.assertTrue(verify_trace(value, corrupted))

        sha512_trace = fixture()
        sha512_trace["runtime"]["conformanceTraces"][0]["digest"] = {
            "algorithm": "sha512",
            "value": "0" * 128,
        }
        self.assertTrue(vao04.schema_errors(sha512_trace, vao04.MANIFEST_SCHEMA))

