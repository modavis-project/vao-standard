    def test_deterministic_renderer_requires_execution_specific_identity(self) -> None:
        value = json.loads(ACOUSTIC_FIXTURE.read_text(encoding="utf-8"))
        value["runtime"]["renderers"][0]["deterministic"] = True
        report = vao04.validate_manifest(value)
        self.assertFalse(report["valid"])
        self.assertTrue(
            any("Renderer" in error and "exact" in error for error in report["errors"]),
            report["errors"],
        )

    def test_reproducibility_requires_code_and_environment_evidence(self) -> None:
        value = fixture()
        analysis = value["scientific"]["analyses"][0]
        environment = next(
            item
            for item in value["scientific"]["softwareEnvironments"]
            if item["id"] == analysis["softwareEnvironmentId"]
        )
        analysis["reproducibility"] = "deterministic"
        environment["identityScope"] = "source-file"
        environment["identityDescription"] = "SHA-256 of the exact analysis source."
        environment["runtimeDescription"] = "CPython 3.14 on a declared target host."
        report = vao04.validate_manifest(value)
        self.assertFalse(report["valid"])
        self.assertTrue(
            any("Analysis" in error and "exact" in error for error in report["errors"])
        )

        environment["dependencies"] = [
            {
                "name": "analysis-environment.lock",
                "dependencyRole": "environment-lock",
                "identity": {"algorithm": "sha256", "value": "1" * 64},
                "identityScope": "environment-lock",
                "identityDescription": "SHA-256 of the exact dependency lock.",
            }
        ]
        self.assertTrue(vao04.validate_manifest(value)["valid"])

        environment["identityScope"] = "environment-lock"
        environment["identityDescription"] = "SHA-256 of only the environment lock."
        environment.pop("dependencies")
        self.assertFalse(vao04.validate_manifest(value)["valid"])

