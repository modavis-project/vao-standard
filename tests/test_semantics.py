        frame.update(
            {
                "coordinateType": "geodetic",
                "handedness": "not-applicable",
                "upAxis": "not-applicable",
                "forwardAxis": "not-applicable",
                "axisUnits": [
                    "http://qudt.org/vocab/unit/DEG",
                    "http://qudt.org/vocab/unit/DEG",
                    "http://qudt.org/vocab/unit/M",
                ],
                "crs": "https://www.opengis.net/def/crs/OGC/1.3/CRS84h",
            }
        )
        frame.pop("unit")
        value["acoustics"]["coordinateFrames"].append(frame)
        pose = value["acoustics"]["poses"][2]
        pose["frameId"] = frame["id"]
        pose.pop("orientationXYZW")
        pose.pop("localFrameId")
        pose["positionUncertainty"] = {
            "kind": "standard",
            "value": [0.00001, 0.00001, 0.02],
            "axisUnits": frame["axisUnits"],
        }
